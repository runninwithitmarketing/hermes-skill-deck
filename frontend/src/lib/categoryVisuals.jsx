export { materials };
export function getCategoryVisual(category = "", index = 0) {
  const paletteEntry = palette[index % palette.length];
  const exactMaterialMatch = exactMaterialMatchers.find((item) => item.test.test(category));
  const materialMatch = materialMatchers.find((item) => item.test.test(category));
  const iconMatch = iconMatchers.find((item) => item.test.test(category));
  const material = exactMaterialMatch?.material || materialMatch?.material || paletteEntry;

  return {
    ...material,
    Icon: iconMatch?.Icon || FolderOpen,
  };
}
